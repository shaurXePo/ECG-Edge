#!/usr/bin/env python3
"""export_headers.py - design the filters, quantise them, and emit C headers + golden reference.

Outputs (default firmware/inc/generated/):
    ecg_params.h   scalars + X-macro lists (sample rate, tap counts, post-shifts ...)
    ecg_coeffs.h   const coefficient arrays (f32 / Q15 / Q31) in CMSIS layout
    ecg_testvec.h  the int16 ECG test segment
Outputs (results/):
    ecg_segment.npz   cached segment (so later runs / footprint builds use the identical data)
    reference.npz     float64 reference outputs for every filter family
    meta.json         everything validate.py needs to know about the build

Examples:
    python scripts/export_headers.py                       # MIT-BIH record 100, first 10 s
    python scripts/export_headers.py --source synthetic    # no network: smoke test only
    python scripts/export_headers.py --fir-taps 63 127 --iir-orders 2
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

BANNER = "/* AUTO-GENERATED by scripts/export_headers.py - DO NOT EDIT BY HAND. */\n"


# ----------------------------------------------------------------------------- C formatting
def c_int_array(name: str, ctype: str, arr, per_line: int = 8, qual: str = "static const") -> str:
    arr = [int(v) for v in arr]
    rows = [", ".join(f"{v:6d}" for v in arr[i:i + per_line]) for i in range(0, len(arr), per_line)]
    return f"{qual} {ctype} {name}[{len(arr)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def c_f32_array(name: str, arr, per_line: int = 4) -> str:
    arr = [float(v) for v in arr]
    rows = [", ".join(f"{v:+.9e}f" for v in arr[i:i + per_line]) for i in range(0, len(arr), per_line)]
    return f"static const float32_t {name}[{len(arr)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


# ----------------------------------------------------------------------------- main logic
def get_segment(args, results: Path):
    cache = results / "ecg_segment.npz"
    if args.headers_only:
        if not cache.exists():
            sys.exit(f"--headers-only needs {cache}; run once without it first.")
        d = np.load(cache, allow_pickle=False)
        return d["x_q15"], d["ann_samples"], d["ann_symbols"], str(d["name"])
    seg = C.load_ecg(args.source, args.record, args.seconds, args.start)
    x_q15 = C.quantize_input(seg["x_mv"])
    rail = int(np.sum((x_q15 == C.Q15_MAX) | (x_q15 == C.Q15_MIN)))
    print(f"[segment] {seg['name']}: {len(x_q15)} samples, peak |x| = {np.max(np.abs(x_q15))} LSB "
          f"({np.max(np.abs(x_q15)) * C.LSB_UV / 1000:.2f} mV), samples at rail: {rail}")
    np.savez(cache, x_q15=x_q15, ann_samples=seg["ann_samples"].astype(int),
             ann_symbols=np.array(seg["ann_symbols"], dtype=str), name=seg["name"])
    return x_q15, seg["ann_samples"], np.array(seg["ann_symbols"], dtype=str), seg["name"]


def build(args):
    results = Path(args.results_dir)
    out = Path(args.out_dir)
    results.mkdir(parents=True, exist_ok=True)
    out.mkdir(parents=True, exist_ok=True)
    x_q15, ann_s, ann_y, seg_name = get_segment(args, results)

    params, coeffs = [BANNER, "#ifndef ECG_PARAMS_H\n#define ECG_PARAMS_H\n\n"], [BANNER, '#include "arm_math_types.h"\n\n']
    meta = dict(segment=seg_name, fs_hz=C.FS_HZ, n_samples=int(len(x_q15)), fullscale_mv=C.FULLSCALE_MV,
                lsb_uv=C.LSB_UV, iir_scale=args.iir_scale, input_sha1=C.sha1_int16(x_q15),
                fir={}, iir={}, pt={}, bp=[C.BP_LO_HZ, C.BP_HI_HZ], notch=[C.NOTCH_HZ, C.NOTCH_Q])
    refs = {}

    params.append(f"#define ECG_FS_HZ            {C.FS_HZ}u      /* sampling rate [Hz] */\n")
    params.append(f"#define ECG_N_SAMPLES        {len(x_q15)}u   /* samples in the stored test vector */\n")
    params.append(f"#define ECG_FULLSCALE_UV     {int(C.FULLSCALE_MV * 1000)}u   /* Q15 full scale = +/- this many microvolts */\n")
    params.append(f'#define ECG_RECORD_NAME      "{seg_name}"\n\n')

    # ---- FIR families ---------------------------------------------------------------
    print("\nFIR band-pass 0.5-40 Hz (Hamming windowed-sinc)")
    print(f"{'taps':>5} {'padded':>6} {'max|h|':>9} {'L1=sum|h|':>10} {'coef-quant err (max)':>22}")
    for n in args.fir_taps:
        h = C.design_fir(n)
        qh, npad = C.fir_to_cmsis_q15(h)
        fh, _ = C.fir_to_cmsis_f32(h)
        l1 = float(np.sum(np.abs(h)))
        qerr = float(np.max(np.abs(C.dequant(qh, 16)[::-1][:n] - h)))
        print(f"{n:5d} {npad:6d} {np.max(np.abs(h)):9.5f} {l1:10.4f} {qerr:22.3e}")
        if np.max(np.abs(h)) >= 1.0:
            sys.exit("FIR coefficient >= 1.0 cannot be represented in Q15; rescale the filter.")
        params.append(f"#define ECG_FIR{n}_NTAPS     {npad}u   /* {n} taps + {npad - n} zero pad (arm_fir_q15 needs an even count) */\n")
        coeffs.append(c_int_array(f"ecg_fir{n}_q15", "q15_t", qh))
        coeffs.append(c_f32_array(f"ecg_fir{n}_f32", fh))
        refs[f"ref_fir{n}"] = C.ref_fir(x_q15, h)
        meta["fir"][str(n)] = dict(padded=npad, l1=l1, gd_samples=(n - 1) / 2, gd_ms=(n - 1) / 2 / C.FS_HZ * 1000)
    params.append("\n#define ECG_FIR_LIST(X) " + " ".join(f"X({n})" for n in args.fir_taps) + "\n\n")

    # ---- IIR families ---------------------------------------------------------------
    print(f"\nIIR Butterworth band-pass + {C.NOTCH_HZ:g} Hz notch (SOS), scaling = {args.iir_scale}")
    print(f"{'order':>5} {'stages':>6} {'max|coef|':>10} {'postShift':>9}  section peak gains")
    for k in args.iir_orders:
        sos0 = C.design_iir_sos(k)
        sos_s = C.scale_sos_linf(sos0) if args.iir_scale == "linf" else sos0
        cm = C.sos_to_cmsis(sos_s)
        ps = C.choose_post_shift(cm)
        q15 = C.q15_biquad_layout(cm, ps)
        q31 = C.quant(cm, 32, ps)
        f32 = C.sos_to_cmsis(sos0)                       # float path uses the unscaled design
        gains = C.sos_peak_gains(sos0)
        print(f"{k:5d} {len(sos0):6d} {np.max(np.abs(cm)):10.5f} {ps:9d}  {np.round(gains, 3)}")
        params.append(f"#define ECG_IIR{k}_STAGES    {len(sos0)}u   /* {k} band-pass sections + 1 notch section */\n")
        params.append(f"#define ECG_IIR{k}_POSTSHIFT {ps}      /* CMSIS postShift: stored coef = real * 2^(15-{ps}) (Q15) */\n")
        coeffs.append(c_f32_array(f"ecg_iir{k}_f32", f32.flatten()))
        coeffs.append(c_int_array(f"ecg_iir{k}_q15", "q15_t", q15.flatten(), per_line=6))
        coeffs.append(c_int_array(f"ecg_iir{k}_q31", "q31_t", q31.flatten(), per_line=5))
        refs[f"ref_iir{k}"] = C.ref_iir(x_q15, sos0)
        meta["iir"][str(k)] = dict(stages=len(sos0), post_shift=ps, max_coef=float(np.max(np.abs(cm))),
                                   gd10_samples=C.group_delay_samples(sos0, 10.0),
                                   gd10_ms=C.group_delay_samples(sos0, 10.0) / C.FS_HZ * 1000,
                                   section_peak_gains=gains.tolist())
    params.append("\n#define ECG_IIR_LIST(X) " + " ".join(f"X({k})" for k in args.iir_orders) + "\n\n")

    # ---- "hp1" structure: 2x 1st-order HP + Butterworth LP + notch (Q15-friendly) ----------
    sos_h0 = C.design_iirh_sos(args.iirh_lp_order)
    sos_h = C.scale_sos_linf(sos_h0) if args.iir_scale == "linf" else sos_h0
    cm_h = C.sos_to_cmsis(sos_h)
    ps_h = C.choose_post_shift(cm_h)
    print(f"\nhp1 structure (2x 1st-order HP + LP{args.iirh_lp_order} + notch): {len(sos_h0)} sections, "
          f"max|coef| {np.max(np.abs(cm_h)):.5f}, postShift {ps_h}")
    params.append(f"#define ECG_IIRH_STAGES      {len(sos_h0)}u   /* 2 first-order HP + {args.iirh_lp_order // 2 + args.iirh_lp_order % 2} LP + 1 notch */\n")
    params.append(f"#define ECG_IIRH_POSTSHIFT   {ps_h}\n\n")
    coeffs.append(c_f32_array("ecg_iirh_f32", C.sos_to_cmsis(sos_h0).flatten()))
    coeffs.append(c_int_array("ecg_iirh_q15", "q15_t", C.q15_biquad_layout(cm_h, ps_h).flatten(), per_line=6))
    coeffs.append(c_int_array("ecg_iirh_q31", "q31_t", C.quant(cm_h, 32, ps_h).flatten(), per_line=5))
    refs["ref_iirh"] = C.ref_iir(x_q15, sos_h0)
    meta["iirh"] = dict(stages=len(sos_h0), post_shift=ps_h, lp_order=args.iirh_lp_order,
                        gd10_samples=C.group_delay_samples(sos_h0, 10.0),
                        gd10_ms=C.group_delay_samples(sos_h0, 10.0) / C.FS_HZ * 1000)

    # ---- Pan-Tompkins band-pass ----------------------------------------------------
    sos_pt = C.design_pt_sos()
    cm_pt = C.sos_to_cmsis(C.scale_sos_linf(sos_pt))
    ps_pt = C.choose_post_shift(cm_pt)
    gd_pt = C.group_delay_samples(sos_pt, 10.0)
    params.append(f"#define ECG_PT_STAGES        {len(sos_pt)}u\n")
    params.append(f"#define ECG_PT_POSTSHIFT     {ps_pt}\n\n")
    coeffs.append(c_int_array("ecg_pt_bp_q15", "q15_t", C.q15_biquad_layout(cm_pt, ps_pt).flatten(), per_line=6))
    meta["pt"] = dict(stages=len(sos_pt), post_shift=ps_pt, bp_gd10_samples=gd_pt, bp=[C.PT_LO_HZ, C.PT_HI_HZ])
    print(f"\nPan-Tompkins 5-15 Hz band-pass: {len(sos_pt)} sections, postShift {ps_pt}, group delay@10Hz = {gd_pt:.1f} samples")

    params.append("#endif /* ECG_PARAMS_H */\n")

    # ---- test vector header --------------------------------------------------------
    tv = [BANNER, f"/* {seg_name}; Q15 full scale = +/-{C.FULLSCALE_MV:g} mV, SHA1(int16 LE) = {meta['input_sha1']} */\n",
          "#include <stdint.h>\n\n",
          c_int_array("ecg_testvec", "int16_t", x_q15, per_line=12)]

    (out / "ecg_params.h").write_text("".join(params))
    (out / "ecg_coeffs.h").write_text("".join(coeffs))
    (out / "ecg_testvec.h").write_text("".join(tv))
    print(f"\n[export] wrote ecg_params.h, ecg_coeffs.h, ecg_testvec.h -> {out}")

    if not args.no_reference:
        np.savez(results / "reference.npz", x=x_q15.astype(float), ann_samples=np.asarray(ann_s, dtype=int),
                 ann_symbols=np.asarray(ann_y, dtype=str), **refs)
        C.save_json(results / "meta.json", meta)
        print(f"[export] wrote {results/'reference.npz'} and {results/'meta.json'}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", choices=["wfdb", "synthetic"], default="wfdb")
    ap.add_argument("--record", default="100")
    ap.add_argument("--seconds", type=float, default=10.0)
    ap.add_argument("--start", type=float, default=0.0, help="segment start [s]")
    ap.add_argument("--fir-taps", type=int, nargs="+", default=list(C.DEFAULT_FIR_TAPS))
    ap.add_argument("--iir-orders", type=int, nargs="+", default=list(C.DEFAULT_IIR_ORDERS))
    ap.add_argument("--iirh-lp-order", type=int, default=2, help="LP order of the hp1 structure")
    ap.add_argument("--iir-scale", choices=["none", "linf"], default="linf")
    ap.add_argument("--out-dir", default=str(C.REPO / "firmware" / "inc" / "generated"))
    ap.add_argument("--results-dir", default=str(C.RESULTS))
    ap.add_argument("--headers-only", action="store_true", help="reuse cached segment, skip download")
    ap.add_argument("--no-reference", action="store_true", help="do not (re)write reference.npz / meta.json")
    build(ap.parse_args())


if __name__ == "__main__":
    main()
